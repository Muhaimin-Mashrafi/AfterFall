package com.afterfall.application.persistence;

import com.afterfall.chapter.ChapterTransition;
import com.afterfall.choice.ChoiceRecord;
import com.afterfall.narrator.StoryCaption;
import com.afterfall.observer.InterventionRecord;

import java.util.List;
import java.util.Optional;

/**
 * Persistence port for simulation runs, lifecycle checkpoints, chapters, choices, interventions, and captions.
 *
 * <p>Implemented by both {@code JpaPostgresRunRepository} and {@code InMemoryRunRepository}.
 */
public interface RunRepository {

    /**
     * Saves or updates simulation run metadata.
     */
    void saveRun(RunMetadata metadata);

    /**
     * Finds simulation run metadata by ID.
     */
    Optional<RunMetadata> findRun(RunId runId);

    /**
     * Records a lightweight simulation checkpoint.
     */
    void saveCheckpoint(RunCheckpoint checkpoint);

    /**
     * Returns all checkpoints recorded for a run in tick order.
     */
    List<RunCheckpoint> checkpointsForRun(RunId runId);

    /**
     * Records a resolved choice moment. Idempotent by choiceId.
     */
    void recordChoice(RunId runId, ChoiceRecord choiceRecord);

    /**
     * Returns all choice records for a run.
     */
    List<ChoiceRecord> choicesForRun(RunId runId);

    /**
     * Records an Observer AI observation or intervention. Idempotent by interventionId.
     */
    void recordIntervention(RunId runId, InterventionRecord interventionRecord);

    /**
     * Returns all intervention records for a run.
     */
    List<InterventionRecord> interventionsForRun(RunId runId);

    /**
     * Records a chapter transition.
     */
    void recordChapterTransition(RunId runId, ChapterTransition transition);

    /**
     * Returns all chapter transitions for a run in tick order.
     */
    List<ChapterTransition> chapterTransitionsForRun(RunId runId);

    /**
     * Records a story caption generated by the Narrator. Idempotent by captionId.
     */
    void recordCaption(RunId runId, StoryCaption caption);

    /**
     * Returns all captions for a run in order.
     */
    List<StoryCaption> captionsForRun(RunId runId);

    /**
     * Loads the consolidated inputs required for the documentary recap (M11).
     */
    RunRecapInputs loadRecapInputs(RunId runId);
}
